const DICTS: Record<Lang, Record<Key, string>> = { en: EN as unknown as Record<Key, string>, pt: PT };

let current: Lang = "en";

export const getLang = (): Lang => current;
export const setLang = (l: Lang) => {
  current = l;
};

/** Texto no idioma atual, com {parâmetros}. Se faltar a chave, cai para inglês e depois para a própria chave. */
export function t(key: Key, params?: Record<string, string | number>): string {
  const s = DICTS[current][key] ?? DICTS.en[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? "")) : s;
}

/** Locale para números e datas. */
export const locale = () => (current === "pt" ? "pt-PT" : "en-IE");

export function detectLang(): Lang {
  try {
    return typeof navigator !== "undefined" && /^pt/i.test(navigator.language) ? "pt" : "en";
  } catch {
    return "en";
  }
}
